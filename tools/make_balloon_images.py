"""Draw the balloon sprites in png/ (red_balloon.png, green_balloon.png).

Run from the repo root: python tools/make_balloon_images.py
Original artwork generated by this script; no external assets or licences.
"""
import os

import numpy as np
from PIL import Image

SIZE = 256   # output size; game.py scales to BALLOON_SIZE
SS = 4       # supersampling for smooth edges

COLORS = {
    "red_balloon.png": (225, 35, 45),
    "green_balloon.png": (40, 190, 70),
}


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0, 1)
    return t * t * (3 - 2 * t)


def balloon(rgb):
    n = SIZE * SS
    y, x = np.mgrid[0:n, 0:n].astype(np.float32) / n  # 0..1

    # Egg-shaped body: wider at the top, tapering toward the knot.
    cx, cy, rx, ry = 0.5, 0.43, 0.36, 0.40
    v = (y - cy) / ry
    taper = 1 - 0.22 * np.clip(v, 0, None) ** 1.5
    d = ((x - cx) / (rx * taper)) ** 2 + v ** 2       # <1 inside
    px = 1.0 / n
    body = smoothstep(1 + 2.5 * px / ry, 1 - 2.5 * px / ry, d)

    # Shading: lit from upper left, darker toward the rim.
    lx, ly = cx - 0.13, cy - 0.17
    dist = np.sqrt(((x - lx) / 0.55) ** 2 + ((y - ly) / 0.6) ** 2)
    base = np.array(rgb, np.float32) / 255
    light = np.clip(1.25 - 0.75 * dist, 0.45, 1.25)[..., None]
    col = np.clip(base * light, 0, 1)
    rim = smoothstep(0.55, 1.0, d)[..., None]
    col = col * (1 - 0.35 * rim)

    # Soft specular highlight (rotated ellipse) plus a small sharp glint.
    hx, hy = cx - 0.15, cy - 0.18
    a = np.deg2rad(-35)
    u = ((x - hx) * np.cos(a) - (y - hy) * np.sin(a)) / 0.07
    w = ((x - hx) * np.sin(a) + (y - hy) * np.cos(a)) / 0.14
    spec = np.exp(-(u ** 2 + w ** 2) * 1.6) * 0.75
    gx, gy = cx - 0.20, cy - 0.06
    glint = np.exp(-(((x - gx) / 0.022) ** 2 + ((y - gy) / 0.035) ** 2)) * 0.6
    col = col + (1 - col) * (spec + glint)[..., None]

    # Knot: small triangle under the body.
    ky = cy + ry * 0.995
    kt = (y - ky) / 0.045
    knot = ((kt >= -0.2) & (kt <= 1) & (np.abs(x - cx) <= 0.012 + 0.022 * np.clip(kt, 0, 1))).astype(np.float32)
    knot_col = base * 0.7

    # String: thin wavy line from the knot to the bottom edge.
    sy0 = ky + 0.045
    sx = cx + 0.025 * np.sin((y - sy0) * 28)
    string = ((y >= sy0) & (np.abs(x - sx) <= 0.0045)).astype(np.float32) * 0.85
    string_col = np.array([0.85, 0.85, 0.85], np.float32)

    rgba = np.zeros((n, n, 4), np.float32)
    for layer, c in ((string, string_col), (knot, knot_col)):
        rgba[..., :3] = rgba[..., :3] * (1 - layer[..., None]) + c * layer[..., None]
        rgba[..., 3] = np.maximum(rgba[..., 3], layer)
    rgba[..., :3] = rgba[..., :3] * (1 - body[..., None]) + col * body[..., None]
    rgba[..., 3] = np.maximum(rgba[..., 3], body)

    # Downsample with premultiplied alpha.
    pre = rgba.copy()
    pre[..., :3] *= pre[..., 3:4]
    pre = pre.reshape(SIZE, SS, SIZE, SS, 4).mean(axis=(1, 3))
    alpha = pre[..., 3:4]
    out = np.where(alpha > 0, pre[..., :3] / np.maximum(alpha, 1e-6), 0)
    img = np.concatenate([out, alpha], axis=-1)
    return Image.fromarray((np.clip(img, 0, 1) * 255 + 0.5).astype(np.uint8), "RGBA")


if __name__ == "__main__":
    os.makedirs("png", exist_ok=True)
    for name, rgb in COLORS.items():
        balloon(rgb).save(os.path.join("png", name))
        print("wrote", os.path.join("png", name))

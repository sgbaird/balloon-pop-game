"""Synthesize sound/nudge_whee.wav: a cartoon slide-whistle "whee-oop" for near misses.

Run from the repo root: python tools/make_sounds.py
Original sound generated by this script; no external assets or licences.
"""
import os
import wave

import numpy as np

RATE = 44100


def whee():
    # Pitch: slide up (whee) with a wobble, then a quick drop (oop)
    up, down = 0.32, 0.14
    t_up = np.linspace(0, up, int(RATE * up), endpoint=False)
    t_dn = np.linspace(0, down, int(RATE * down), endpoint=False)
    f_up = 420 + (1150 - 420) * (t_up / up) ** 0.7
    f_up *= 1 + 0.035 * np.sin(2 * np.pi * 11 * t_up)          # vibrato
    f_dn = 1150 - (1150 - 560) * (t_dn / down) ** 1.5
    freq = np.concatenate([f_up, f_dn])
    phase = 2 * np.pi * np.cumsum(freq) / RATE
    tone = np.sin(phase) + 0.25 * np.sin(2 * phase) + 0.08 * np.sin(3 * phase)
    breath = np.random.default_rng(0).normal(0, 0.04, tone.size)  # a little air, like a whistle
    sig = tone + breath

    n = sig.size
    env = np.ones(n)
    a, r = int(0.012 * RATE), int(0.06 * RATE)
    env[:a] = np.linspace(0, 1, a)
    env[-r:] = np.linspace(1, 0, r)
    sig *= env
    sig /= np.abs(sig).max()
    return (sig * 0.8 * 32767).astype(np.int16)


if __name__ == "__main__":
    os.makedirs("sound", exist_ok=True)
    path = os.path.join("sound", "nudge_whee.wav")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(whee().tobytes())
    print("wrote", path)
